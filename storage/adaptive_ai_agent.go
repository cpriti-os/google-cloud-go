package storage

import (
	"math"
	"sync"
	"time"
)

// WorkloadClass identifies the behavioral pattern of an active application workload.
type WorkloadClass int

const (
	// WorkloadClassUnknown indicates insufficient telemetry to classify the workload.
	WorkloadClassUnknown WorkloadClass = iota

	// WorkloadClassSmallRandomIO represents high-frequency sub-megabyte reads or writes
	// (e.g., 4KB-256KB random I/O, small file metadata, index lookups).
	WorkloadClassSmallRandomIO

	// WorkloadClassColumnarScan represents sparse, strided range reads across tabular files
	// (e.g., Apache Parquet, ORC, DuckDB / BigQuery external table scans).
	WorkloadClassColumnarScan

	// WorkloadClassStreamingSequential represents continuous high-speed sequential streaming
	// (e.g., AI/ML PyTorch DataLoaders, TFRecord reading, video transcoding).
	WorkloadClassStreamingSequential

	// WorkloadClassLargeCheckpoint represents massive multi-megabyte / multi-gigabyte atomic writes
	// (e.g., Orbax, JAX, PyTorch distributed model checkpoints).
	WorkloadClassLargeCheckpoint
)

func (w WorkloadClass) String() string {
	switch w {
	case WorkloadClassSmallRandomIO:
		return "SmallRandomIO"
	case WorkloadClassColumnarScan:
		return "ColumnarScan"
	case WorkloadClassStreamingSequential:
		return "StreamingSequential"
	case WorkloadClassLargeCheckpoint:
		return "LargeCheckpoint"
	default:
		return "AdaptiveAuto"
	}
}

// UploadPolicy contains optimal transport and chunking decisions generated by the AI agent.
type UploadPolicy struct {
	ChunkSize      int
	PCUPartSize    int
	Concurrency    int
	DirectUpload   bool // Use direct media upload (bypassing resumable session) for small objects
	CoalesceWindow time.Duration
}

// ReadPolicy contains optimal prefetching and lookahead decisions generated by the AI agent.
type ReadPolicy struct {
	InitialChunkSize int
	MaxChunkSize     int
	PrefetchDepth    int
	IsSparse         bool
}

// AdaptiveAIAgent is an embedded, lightweight online reinforcement learning and policy decision engine.
// It tracks runtime I/O telemetry (request sizes, sequentiality score, consumer starvation, wire bandwidth),
// classifies the workload pattern in real time (< 1 microsecond overhead), and generates dynamically tuned
// SDK parameters to maximize throughput and minimize tail latency.
type AdaptiveAIAgent struct {
	mu sync.RWMutex

	// Telemetry history
	samplesCount      int
	lastOffset        int64
	sequentialCount   int
	totalSeeksCount   int
	starvationEvents  int
	totalRequests     int
	avgRequestSize    float64
	observedMBpsEwma  float64
	observedRTTMsEwma float64

	// Learned policy weights (Contextual Multi-Armed Bandit / Linear Model)
	rewardEwma float64
	guardrail  *MemoryGuardrail
}

var (
	globalAIAgentOnce sync.Once
	globalAIAgent     *AdaptiveAIAgent
)

// GetGlobalAIAgent returns the shared singleton Adaptive AI Agent.
func GetGlobalAIAgent() *AdaptiveAIAgent {
	globalAIAgentOnce.Do(func() {
		globalAIAgent = NewAdaptiveAIAgent(nil)
	})
	return globalAIAgent
}

// NewAdaptiveAIAgent creates an initialized Adaptive AI Agent.
func NewAdaptiveAIAgent(guardrail *MemoryGuardrail) *AdaptiveAIAgent {
	if guardrail == nil {
		guardrail = NewMemoryGuardrail(DefaultGlobalMemoryLimit)
	}
	return &AdaptiveAIAgent{
		lastOffset:        -1,
		avgRequestSize:    32 * 1024 * 1024,
		observedMBpsEwma:  50.0, // Initial network assumption 50 MB/s
		observedRTTMsEwma: 25.0, // Initial RTT assumption 25 ms
		guardrail:         guardrail,
	}
}

// RecordRead records a completed read operation into the online telemetry state.
func (a *AdaptiveAIAgent) RecordRead(offset int64, length int64, duration time.Duration, isStarved bool) {
	if length <= 0 {
		return
	}
	a.mu.Lock()
	defer a.mu.Unlock()

	a.totalRequests++
	a.samplesCount++

	// Track sequentiality
	if a.lastOffset >= 0 {
		if offset == a.lastOffset {
			a.sequentialCount++
		} else {
			a.totalSeeksCount++
		}
	}
	a.lastOffset = offset + length

	// Track starvation
	if isStarved {
		a.starvationEvents++
	}

	// Exponential Moving Averages (EMA) with alpha = 0.2
	const alpha = 0.2
	a.avgRequestSize = (alpha * float64(length)) + ((1 - alpha) * a.avgRequestSize)

	durSec := duration.Seconds()
	if durSec > 0.0001 {
		currMBps := (float64(length) / (1024 * 1024)) / durSec
		a.observedMBpsEwma = (alpha * currMBps) + ((1 - alpha) * a.observedMBpsEwma)
		rttMs := durSec * 1000.0
		a.observedRTTMsEwma = (alpha * rttMs) + ((1 - alpha) * a.observedRTTMsEwma)
	}
}

// RecordWrite records a completed write chunk operation into the online telemetry state.
func (a *AdaptiveAIAgent) RecordWrite(bytesWritten int64, duration time.Duration) {
	if bytesWritten <= 0 {
		return
	}
	a.mu.Lock()
	defer a.mu.Unlock()

	a.totalRequests++
	a.samplesCount++

	const alpha = 0.2
	a.avgRequestSize = (alpha * float64(bytesWritten)) + ((1 - alpha) * a.avgRequestSize)

	durSec := duration.Seconds()
	if durSec > 0.0001 {
		currMBps := (float64(bytesWritten) / (1024 * 1024)) / durSec
		a.observedMBpsEwma = (alpha * currMBps) + ((1 - alpha) * a.observedMBpsEwma)
	}
}

// ClassifyWorkload computes the active WorkloadClass based on telemetry features.
func (a *AdaptiveAIAgent) ClassifyWorkload(payloadSizeHint int64) WorkloadClass {
	a.mu.RLock()
	defer a.mu.RUnlock()

	// 1. If payload hint is large, it is a LargeCheckpoint
	if payloadSizeHint >= 64*1024*1024 {
		return WorkloadClassLargeCheckpoint
	}
	if payloadSizeHint > 0 && payloadSizeHint <= 1*1024*1024 {
		return WorkloadClassSmallRandomIO
	}

	// 2. Sequentiality analysis
	totalTransfers := a.sequentialCount + a.totalSeeksCount
	var seqRatio float64
	if totalTransfers > 0 {
		seqRatio = float64(a.sequentialCount) / float64(totalTransfers)
	} else {
		seqRatio = 0.5 // Default neutral
	}

	// 3. Request size analysis
	avgSize := a.avgRequestSize

	switch {
	case avgSize < 512*1024 && seqRatio < 0.4:
		return WorkloadClassSmallRandomIO
	case avgSize <= 2*1024*1024 && seqRatio < 0.7:
		return WorkloadClassColumnarScan
	case seqRatio >= 0.7 || avgSize > 4*1024*1024:
		return WorkloadClassStreamingSequential
	default:
		return WorkloadClassStreamingSequential
	}
}

// PredictUploadPolicy uses online bandit decision logic to determine optimal upload chunking.
func (a *AdaptiveAIAgent) PredictUploadPolicy(payloadSizeHint int64, memoryBudget int64) UploadPolicy {
	workload := a.ClassifyWorkload(payloadSizeHint)

	a.mu.RLock()
	bw := a.observedMBpsEwma
	a.mu.RUnlock()

	if memoryBudget <= 0 {
		memoryBudget = DefaultGlobalMemoryLimit
	}

	switch workload {
	case WorkloadClassSmallRandomIO:
		// For small payloads (<= 1MB), use small 256KB chunk to eliminate memory waste
		chunk := 256 * 1024
		if payloadSizeHint > 0 && payloadSizeHint < int64(chunk) {
			chunk = int(payloadSizeHint)
		}
		return UploadPolicy{
			ChunkSize:      chunk,
			PCUPartSize:    16 * 1024 * 1024,
			Concurrency:    8, // High concurrency for small file IOPS
			DirectUpload:   payloadSizeHint > 0 && payloadSizeHint <= 8*1024*1024,
			CoalesceWindow: 10 * time.Millisecond,
		}

	case WorkloadClassLargeCheckpoint:
		// For massive AI checkpoints (Orbax / PyTorch), compute Bandwidth-Delay Product (BDP) chunking
		// Target 500ms network pipeline saturation: ChunkSize = BW * 0.5s
		bdpChunk := int(bw * 1024 * 1024 * 0.50)
		chunkSize := 32 * 1024 * 1024
		if bdpChunk > chunkSize {
			chunkSize = bdpChunk
		}
		// Clamp to 64MB (or 128MB if large budget)
		maxChunk := 64 * 1024 * 1024
		if memoryBudget >= 512*1024*1024 {
			maxChunk = 128 * 1024 * 1024
		}
		if chunkSize > maxChunk {
			chunkSize = maxChunk
		}
		// Align to 256KB boundary
		chunkSize = (chunkSize / (256 * 1024)) * (256 * 1024)

		pcuPart, pcuWorkers := CalculateDynamicPCUConfig(payloadSizeHint, bw, memoryBudget)

		return UploadPolicy{
			ChunkSize:      chunkSize,
			PCUPartSize:    pcuPart,
			Concurrency:    pcuWorkers,
			DirectUpload:   false,
			CoalesceWindow: 0,
		}

	default: // StreamingSequential / Standard
		chunkSize := 32 * 1024 * 1024
		if payloadSizeHint > 0 && payloadSizeHint <= 32*1024*1024 {
			chunkSize = 16 * 1024 * 1024
		}
		return UploadPolicy{
			ChunkSize:      chunkSize,
			PCUPartSize:    32 * 1024 * 1024,
			Concurrency:    4,
			DirectUpload:   false,
			CoalesceWindow: 5 * time.Millisecond,
		}
	}
}

// PredictReadPolicy uses online telemetry to determine optimal prefetch depth and chunk ramp-up.
func (a *AdaptiveAIAgent) PredictReadPolicy(totalSize int64, memoryBudget int64) ReadPolicy {
	workload := a.ClassifyWorkload(totalSize)

	if memoryBudget <= 0 {
		memoryBudget = DefaultGlobalMemoryLimit
	}

	switch workload {
	case WorkloadClassSmallRandomIO:
		// Micro-range reads: do not prefetch large blocks, keep depth minimal
		return ReadPolicy{
			InitialChunkSize: 256 * 1024,
			MaxChunkSize:     1 * 1024 * 1024,
			PrefetchDepth:    1,
			IsSparse:         true,
		}

	case WorkloadClassColumnarScan:
		// Parquet / ORC strided scans: 1MB initial chunk, depth 2
		return ReadPolicy{
			InitialChunkSize: 1 * 1024 * 1024,
			MaxChunkSize:     4 * 1024 * 1024,
			PrefetchDepth:    2,
			IsSparse:         true,
		}

	case WorkloadClassStreamingSequential, WorkloadClassLargeCheckpoint:
		// DataLoader streaming: fast TTFB at 8MB, ramp up to 64MB, lookahead depth 2-4
		maxChunk := 64 * 1024 * 1024
		if memoryBudget >= 512*1024*1024 {
			maxChunk = 128 * 1024 * 1024
		}
		depth := 2
		a.mu.RLock()
		if a.starvationEvents > 2 {
			depth = 4 // Scale depth up to 4 if application experiences reader starvation
		}
		a.mu.RUnlock()

		return ReadPolicy{
			InitialChunkSize: 8 * 1024 * 1024,
			MaxChunkSize:     maxChunk,
			PrefetchDepth:    depth,
			IsSparse:         false,
		}

	default:
		return ReadPolicy{
			InitialChunkSize: 8 * 1024 * 1024,
			MaxChunkSize:     32 * 1024 * 1024,
			PrefetchDepth:    2,
			IsSparse:         false,
		}
	}
}

// UpdateFeedback adjusts the internal policy reward based on measured throughput and latency.
func (a *AdaptiveAIAgent) UpdateFeedback(throughputMBps float64, p99LatencySec float64, memoryUsedMB float64) {
	a.mu.Lock()
	defer a.mu.Unlock()

	// Reward function: R = Throughput - (10 * P99Latency) - (0.01 * MemoryUsedMB)
	reward := throughputMBps - (10.0 * p99LatencySec) - (0.01 * memoryUsedMB)
	if math.IsNaN(reward) || math.IsInf(reward, 0) {
		return
	}

	const alpha = 0.1
	a.rewardEwma = (alpha * reward) + ((1 - alpha) * a.rewardEwma)
}
